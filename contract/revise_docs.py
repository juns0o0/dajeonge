def revise(name, out_name, rules):
    z = zipfile.ZipFile(SRC / name)
    xml = z.read("word/document.xml").decode("utf-8")
    paras = re.findall(r"<w:p[ >].*?</w:p>", xml, flags=re.S)
    used = set()
    def para_text(p):
        return html.unescape("".join(re.findall(r"<w:t(?: [^>]*)?>(.*?)</w:t>", p, flags=re.S)))
    def set_text(p, new_t):
        ts = list(re.finditer(r"<w:t(?: [^>]*)?>(.*?)</w:t>", p, flags=re.S))
        esc = html.escape(new_t, quote=False)
        first = ts[0]
        np_ = p[:first.start(1)] + esc + p[first.end(1):]
        offset = len(np_) - len(p)
        for m in ts[1:]:
            s_, e_ = m.start(1) + offset, m.end(1) + offset
            np_ = np_[:s_] + np_[e_:]; offset -= (e_ - s_)
        return np_.replace('<w:t>', '<w:t xml:space="preserve">', 1) if '<w:t>' in np_ else np_
    for p in paras:
        t = para_text(p)
        new_t = t; extra = []
        for rule in rules:
            old, new = rule[0], rule[1]
            if old in new_t:
                new_t = new_t.replace(old, new); used.add(old)
                if len(rule) > 2: extra.append(rule[2])
        if new_t == t and not extra:
            continue
        if extra:   # 같은 서식의 문단을 뒤에 복제해 추가
            np_ = set_text(p, new_t) + "".join(set_text(p, x) for x in extra)
            xml = xml.replace(p, np_, 1); continue
        ts = list(re.finditer(r"<w:t(?: [^>]*)?>(.*?)</w:t>", p, flags=re.S))
        esc = html.escape(new_t, quote=False)
        first = ts[0]
        np_ = p[:first.start(1)] + esc + p[first.end(1):]
        # 첫 run 이후의 텍스트는 비운다 (서식은 그대로)
        offset = len(np_) - len(p)
        for m in ts[1:]:
            s, e = m.start(1) + offset, m.end(1) + offset
            np_ = np_[:s] + np_[e:]; offset -= (e - s)
        np_ = np_.replace('<w:t>', '<w:t xml:space="preserve">', 1) if '<w:t>' in np_ else np_
        xml = xml.replace(p, np_, 1)
    missing = [r[0] for r in rules if r[0] not in used]
    if missing:
        print(f"[{name}] 치환 못 한 항목:", *missing, sep="\n  ")
    with zipfile.ZipFile(OUT / out_name, "w", zipfile.ZIP_DEFLATED) as zo:
        for item in z.infolist():
            data = xml.encode("utf-8") if item.filename == "word/document.xml" else z.read(item.filename)
            zo.writestr(item, data)
    print("wrote", OUT / out_name)

